// Content ledger (brief WS13). Source of truth: docs/seo/ledger.csv. Renders docs/seo/ledger.md and applies the gate:
// the next batch may ship only when the previous batch is at least 70% indexed (day 28 if filled, else day 14).
// Fill the CSV from Search Console (Page indexing, Performance) at 14 and 28 days after each URL ships.
// Run: npm run ledger
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CSV = path.join(ROOT, 'docs', 'seo', 'ledger.csv');
const MD = path.join(ROOT, 'docs', 'seo', 'ledger.md');
const THRESHOLD = 0.7;

function parseCsv(text) {
  const rows = []; let row = []; let cell = ''; let q = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) { if (c === '"' && text[i + 1] === '"') { cell += '"'; i++; } else if (c === '"') q = false; else cell += c; }
    else if (c === '"') q = true;
    else if (c === ',') { row.push(cell); cell = ''; }
    else if (c === '\n') { row.push(cell.replace(/\r$/, '')); rows.push(row); row = []; cell = ''; }
    else cell += c;
  }
  if (cell || row.length) { row.push(cell); rows.push(row); }
  return rows;
}

const [head, ...body] = parseCsv(readFileSync(CSV, 'utf8').replace(/^﻿/, '')).filter((r) => r.length > 1);
const data = body.map((r) => Object.fromEntries(head.map((h, i) => [h, (r[i] || '').trim()])));
const batches = [...new Set(data.map((d) => d.batch))];
const yes = (v) => /^(y|yes|sim|s|true|1)$/i.test(v);
const filled = (v) => v !== '';

const summary = batches.map((b) => {
  const rows = data.filter((d) => d.batch === b);
  const shipped = rows.filter((r) => filled(r.shipped_on)).length;
  const useD28 = rows.some((r) => filled(r.d28_indexed));
  const key = useD28 ? 'd28_indexed' : 'd14_indexed';
  const checked = rows.filter((r) => filled(r[key])).length;
  const indexed = rows.filter((r) => yes(r[key])).length;
  const rate = shipped ? indexed / shipped : null;
  const revenue = rows.reduce((s, r) => s + (parseFloat(r.revenue_28d_eur.replace(',', '.')) || 0), 0);
  return { b, n: rows.length, shipped, checked, indexed, rate, basis: useD28 ? 'day 28' : 'day 14', revenue, rows };
});

let md = `# Content ledger\n\nGenerated by \`npm run ledger\` from [ledger.csv](ledger.csv). Do not edit this file; edit the CSV.\n\n`;
md += `**Gate:** the next batch may ship only when the previous batch is at least ${THRESHOLD * 100}% indexed (day 28 if filled, else day 14). Batches hold at most 10 URLs, except batch 0, the launch set.\n\n`;
md += `| Batch | URLs | Shipped | Checked | Indexed | Rate | Basis | Revenue 28 d (€) | Next batch |\n|---|---|---|---|---|---|---|---|---|\n`;
const gate = [];
summary.forEach((s, i) => {
  const next = summary[i + 1];
  let status = '';
  if (next) {
    if (s.shipped === 0) status = 'waits (this batch has not shipped)';
    else if (s.rate === null || s.checked < s.shipped) status = 'blocked: indexing not yet checked';
    else if (s.rate >= THRESHOLD) status = `open (${Math.round(s.rate * 100)}%)`;
    else status = `**blocked** (${Math.round(s.rate * 100)}% < ${THRESHOLD * 100}%)`;
    gate.push(`${s.b} → ${next.b}: ${status.replace(/\*\*/g, '')}`);
  }
  md += `| ${s.b} | ${s.n} | ${s.shipped} | ${s.checked} | ${s.indexed} | ${s.rate === null ? '' : Math.round(s.rate * 100) + '%'} | ${s.basis} | ${s.revenue ? s.revenue.toFixed(2) : ''} | ${status} |\n`;
});
for (const s of summary) {
  md += `\n## Batch ${s.b}\n\n| URL | Target keyword | Shipped | d14 indexed | d14 impr. | d14 clicks | d14 pos. | d28 indexed | d28 impr. | d28 clicks | d28 pos. | Revenue (€) |\n|---|---|---|---|---|---|---|---|---|---|---|---|\n`;
  for (const r of s.rows) md += `| \`${r.url}\` | ${r.target_keyword} | ${r.shipped_on} | ${r.d14_indexed} | ${r.d14_impressions} | ${r.d14_clicks} | ${r.d14_position} | ${r.d28_indexed} | ${r.d28_impressions} | ${r.d28_clicks} | ${r.d28_position} | ${r.revenue_28d_eur} |\n`;
}
writeFileSync(MD, md);
console.log('Ledger written to docs/seo/ledger.md\n');
for (const s of summary) console.log(`${s.b.padEnd(18)} ${String(s.n).padStart(2)} URLs, ${s.shipped} shipped, ${s.indexed} indexed${s.rate === null ? '' : ` (${Math.round(s.rate * 100)}%, ${s.basis})`}`);
console.log('\nGate:\n  ' + gate.join('\n  '));
// Exit 1 only if a later batch has shipped while an earlier one is below the threshold.
let violation = false;
summary.forEach((s, i) => { const next = summary[i + 1]; if (next && next.shipped > 0 && (s.rate === null || s.rate < THRESHOLD)) { violation = true; console.log(`\n✗ Batch ${next.b} shipped while ${s.b} is below ${THRESHOLD * 100}% indexed.`); } });
process.exit(violation ? 1 : 0);
