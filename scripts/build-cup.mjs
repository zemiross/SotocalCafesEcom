// Generates snippets/cup-svg.liquid: the Sotocal cup as inline SVG, built from the brief §7 spec
// (the mockup files were not supplied, DECISIONS D05). All geometry is in millimetres.
// Refit: change the constants below, run `node scripts/build-cup.mjs`, and cup.js reads the same numbers
// from the data-geom attribute, so the animation follows automatically.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

// Physical cup (brief §7)
const RIM_IN = 30;      // inner rim radius (Ø 60 mm)
const BASE_IN = 19;     // inner base radius (Ø 38 mm)
const DEPTH = 47;       // inner depth
const FULL_H = 36;      // on-screen full level: fuller than the mockup's 30 ml band at 20.7 mm (client, 30/10/2026; D57)
const LIP = 2;          // rim lip thickness
const BASE_T = 5;       // base thickness under the inner base
const R_OUT_BOTTOM = 21;
// View: seated, ~58° above the table, handle right
const S = 0.848;        // sin 58°: ellipse ry/rx
const C = 0.5299;       // cos 58°: vertical foreshortening of heights
// Placement in the viewBox
const W = 140, H = 130, CX = 70, RIM_CY = 46;

const r = (h) => BASE_IN + ((RIM_IN - BASE_IN) * h) / DEPTH;
const cyAt = (h) => RIM_CY + (DEPTH - h) * C;
const f = (n) => Math.round(n * 1000) / 1000;

const outer = RIM_IN + LIP;
const bottomCy = RIM_CY + (DEPTH + BASE_T) * C;
const saucer = { cy: bottomCy + 1.2, rx: 62, ry: 62 * S };

// Far-wall text paths. Glyphs are squashed vertically by C (wall seen at an angle): the group is scaled (1, C),
// so the path is written in pre-scale space (y / C).
const wallArc = (h, a0 = 158, a1 = 22) => {
  const rr = r(h), cy = cyAt(h) / C, ry = (rr * S) / C;
  const p = (a) => [CX + rr * Math.cos((a * Math.PI) / 180), cy - ry * Math.sin((a * Math.PI) / 180)];
  const [x0, y0] = p(a0), [x1, y1] = p(a1);
  return `M${f(x0)} ${f(y0)}A${f(rr)} ${f(ry)} 0 0 1 ${f(x1)} ${f(y1)}`;
};

const baseCy = cyAt(0);
const fullCy = cyAt(FULL_H);
const geom = { CX, RIM_CY, DEPTH, FULL_H, BASE_IN, RIM_IN, S, C, W, H };

const svg = `{%- comment -%}
  GENERATED by scripts/build-cup.mjs — edit the constants there, not this file.
  The Sotocal cup (brief §7): seated, ~58° view, handle right; inner lettering on side A; base decal with a "1960" mark.
  Params: state ('full' default | 'empty'), class. Full is the static / reduced-motion state; cup.js animates from empty.
{%- endcomment -%}
{%- liquid
  assign cup_state = state | default: 'full'
  if cup_state == 'empty'
    assign surface_t = 'translate(${CX} ${f(baseCy)}) scale(1)'
  else
    assign surface_t = 'translate(${CX} ${f(fullCy)}) scale(${f(r(FULL_H) / BASE_IN)})'
  endif
-%}
<svg class="cup {{ class }}" data-cup data-state="{{ cup_state }}" viewBox="0 0 ${W} ${H}" role="img"
     aria-labelledby="CupTitle" data-geom='${JSON.stringify(geom)}'>
  <title id="CupTitle">{{ 'home.cup.svg_title' | t }}</title>
  <defs>
    <linearGradient id="cupBody" gradientUnits="userSpaceOnUse" x1="${CX - outer}" x2="${CX + outer}" y1="0" y2="0">
      <stop offset="0" stop-color="#140000"/><stop offset=".28" stop-color="#4A1712"/><stop offset=".55" stop-color="#210000"/><stop offset="1" stop-color="#0C0000"/>
    </linearGradient>
    <linearGradient id="cupLip" gradientUnits="userSpaceOnUse" x1="${CX - outer}" x2="${CX + outer}" y1="0" y2="0">
      <stop offset="0" stop-color="#2a0603"/><stop offset=".3" stop-color="#6a2a20"/><stop offset=".6" stop-color="#3a0e09"/><stop offset="1" stop-color="#160201"/>
    </linearGradient>
    <linearGradient id="cupWall" x1="0" x2="0" y1="0" y2="1">
      <stop offset="0" stop-color="#EFD9A6"/><stop offset=".6" stop-color="#FCEFCC"/><stop offset="1" stop-color="#F6E3B4"/>
    </linearGradient>
    <radialGradient id="cupBase">
      <stop offset="0" stop-color="#FFF7DE"/><stop offset=".85" stop-color="#FCEFCC"/><stop offset="1" stop-color="#EBD4A0"/>
    </radialGradient>
    <radialGradient id="cupEspresso" cx=".5" cy=".45" r=".6">
      <stop offset="0" stop-color="#3A1A0B"/><stop offset=".7" stop-color="#220C04"/><stop offset="1" stop-color="#120401"/>
    </radialGradient>
    <radialGradient id="cupCrema" cx=".5" cy=".5" r=".5">
      <stop offset="0" style="stop-color: color-mix(in oklab, #AE5041 55%, #3A1A0B)"/>
      <stop offset=".78" style="stop-color: color-mix(in oklab, #AE5041 45%, #8a5030)"/>
      <stop offset="1" style="stop-color: color-mix(in oklab, #AE5041 35%, #FCEFCC)"/>
    </radialGradient>
    <radialGradient id="cupFoam">
      <stop offset="0" style="stop-color: color-mix(in oklab, #FCEFCC 88%, #AE5041)"/>
      <stop offset=".72" style="stop-color: color-mix(in oklab, #FCEFCC 70%, #AE5041)"/>
      <stop offset="1" style="stop-color: color-mix(in oklab, #FCEFCC 45%, #AE5041); stop-opacity: 0"/>
    </radialGradient>
    <radialGradient id="cupSaucerShadow">
      <stop offset=".6" stop-color="#120000" stop-opacity=".55"/><stop offset="1" stop-color="#120000" stop-opacity="0"/>
    </radialGradient>
    <linearGradient id="cupPour" gradientUnits="objectBoundingBox" x1="0" x2="1" y1="0" y2="0">
      <stop offset="0" stop-color="#0C0000"/><stop offset=".45" stop-color="#3A1A0B"/><stop offset=".7" stop-color="#210000"/><stop offset="1" stop-color="#0C0000"/>
    </linearGradient>
    <filter id="cupTiger" x="0" y="0" width="1" height="1">
      <feTurbulence type="fractalNoise" baseFrequency="0.06 0.9" numOctaves="2" seed="7"/>
      <feColorMatrix values="0 0 0 0 .23  0 0 0 0 .1  0 0 0 0 .04  0 0 0 1.6 -.75"/>
    </filter>
    <clipPath id="cupOpening"><ellipse cx="${CX}" cy="${RIM_CY}" rx="${RIM_IN}" ry="${f(RIM_IN * S)}"/></clipPath>
    <clipPath id="cupSurfaceClip"><ellipse cx="0" cy="0" rx="${BASE_IN}" ry="${f(BASE_IN * S)}"/></clipPath>
  </defs>

  <!-- Saucer -->
  <ellipse cx="${CX}" cy="${f(saucer.cy + 3)}" rx="${f(saucer.rx + 4)}" ry="${f(saucer.ry + 3)}" fill="url(#cupSaucerShadow)"/>
  <ellipse cx="${CX}" cy="${f(saucer.cy + 1.6)}" rx="${saucer.rx}" ry="${f(saucer.ry)}" fill="#120000"/>
  <ellipse cx="${CX}" cy="${f(saucer.cy)}" rx="${saucer.rx}" ry="${f(saucer.ry)}" fill="#2E0A06"/>
  <ellipse cx="${CX}" cy="${f(saucer.cy)}" rx="${f(saucer.rx * 0.91)}" ry="${f(saucer.ry * 0.91)}" fill="none" stroke="#AE5041" stroke-width=".55"/>
  <ellipse cx="${CX}" cy="${f(saucer.cy)}" rx="${f(R_OUT_BOTTOM + 4)}" ry="${f((R_OUT_BOTTOM + 4) * S)}" fill="#1A0201"/>

  <!-- Handle (right), behind the body edge -->
  <path d="M${CX + outer - 3} ${RIM_CY + 6}c9-1 17 1 17 8s-6 12-15 12" fill="none" stroke="url(#cupBody)" stroke-width="5.2" stroke-linecap="round"/>
  <path d="M${CX + outer - 1} ${RIM_CY + 5.4}c7 0 13 1.6 13.6 7" fill="none" stroke="#6a2a20" stroke-width=".8" stroke-linecap="round" opacity=".7"/>

  <!-- Body -->
  <path d="M${CX - outer} ${RIM_CY}C${CX - outer} ${f(RIM_CY + 16)} ${CX - R_OUT_BOTTOM - 6} ${f(bottomCy - 4)} ${CX - R_OUT_BOTTOM} ${f(bottomCy)}A${R_OUT_BOTTOM} ${f(R_OUT_BOTTOM * S)} 0 0 0 ${CX + R_OUT_BOTTOM} ${f(bottomCy)}C${CX + R_OUT_BOTTOM + 6} ${f(bottomCy - 4)} ${CX + outer} ${f(RIM_CY + 16)} ${CX + outer} ${RIM_CY}A${outer} ${f(outer * S)} 0 0 0 ${CX - outer} ${RIM_CY}Z" fill="url(#cupBody)"/>
  <ellipse cx="${CX}" cy="${RIM_CY}" rx="${outer}" ry="${f(outer * S)}" fill="url(#cupLip)"/>

  <!-- Inside (clipped to the opening) -->
  <g clip-path="url(#cupOpening)">
    <rect x="${CX - RIM_IN}" y="${f(RIM_CY - RIM_IN * S)}" width="${RIM_IN * 2}" height="${f(RIM_IN * S * 2)}" fill="url(#cupWall)"/>
    <ellipse cx="${CX}" cy="${f(baseCy)}" rx="${BASE_IN}" ry="${f(BASE_IN * S)}" fill="url(#cupBase)"/>

    <!-- Base decal (client mockup "Sotocal Espresso Cup.pdf"): accent ring, the arrow's last stretch and head, and, on
         screen, the 1960 mark in place of the QR (brief §7) with "Shop online here" -->
    <g transform="translate(${CX} ${f(baseCy)}) scale(1 ${S})" fill="#210000">
      <circle r="${f(BASE_IN * 0.8)}" fill="none" stroke="#AE5041" stroke-width=".6"/>
      <text y="-5.4" text-anchor="middle" font-family="DM Serif Display, Georgia, serif" font-size="5.2" fill="#AE5041">1960</text>
      <text y="-1.2" text-anchor="middle" font-family="Inter, Arial, sans-serif" font-weight="700" font-size="1.9">Shop online here</text>
      <path d="M${f(BASE_IN * 0.95)} -9c-2 1.6-3.4 2.8-4.6 4.2" fill="none" stroke="#AE5041" stroke-width=".6" stroke-linecap="round"/>
      <path d="M${f(BASE_IN * 0.95 - 5.6)} -6.1l.9 1.5 1.6-.6" fill="none" stroke="#AE5041" stroke-width=".6" stroke-linecap="round" stroke-linejoin="round"/>
    </g>

    <!-- Side A lettering on the far wall, following the wall curve (squashed by cos 58°). Heights follow the client mockup:
         "Orgulhosamente Português" sits in the 50–75% band (11.5–16.3 mm above the base), "Português?" in the 75–100%
         band (16.3–20.7 mm), so a full serve covers both and each line appears at its reveal level. Letters ≤ 2.6 mm.
         The mockup writes "¿Português?"; the brief asks for no inverted ¿ (DECISIONS D06, D47). -->
    <g transform="scale(1 ${C})">
      <path id="cupArcLow" d="${wallArc(12.4, 170, 10)}" fill="none"/>
      <path id="cupArcHigh" d="${wallArc(17.4, 150, 30)}" fill="none"/>
      <text font-family="Inter, Arial, sans-serif" font-weight="700" font-size="4.9" fill="#210000">
        <textPath href="#cupArcLow" startOffset="50%" text-anchor="middle">Orgulhosamente Português</textPath>
      </text>
      <text font-family="DM Serif Display, Georgia, serif" font-size="4.6" fill="#AE5041">
        <textPath href="#cupArcHigh" startOffset="50%" text-anchor="middle">Português?</textPath>
      </text>
    </g>

    <!-- Espresso: a unit ellipse at the base radius, moved/scaled as the level rises (transform only) -->
    <g class="cup__surface" data-cup-surface transform="{{ surface_t }}"{% if cup_state == 'empty' %} opacity="0"{% endif %}>
      <ellipse rx="${BASE_IN}" ry="${f(BASE_IN * S)}" fill="url(#cupEspresso)"/>
      <g class="cup__crema" data-cup-crema{% if cup_state == 'empty' %} opacity="0"{% endif %}>
        <ellipse rx="${f(BASE_IN * 0.97)}" ry="${f(BASE_IN * 0.97 * S)}" fill="url(#cupCrema)"/>
        <g clip-path="url(#cupSurfaceClip)" opacity=".38"><rect x="-${BASE_IN}" y="-${f(BASE_IN * S)}" width="${BASE_IN * 2}" height="${f(BASE_IN * S * 2)}" filter="url(#cupTiger)"/></g>
        <!-- A coffee bean drawn in the crema (client, 30/10/2026): pale foam with the bean's S-shaped crease, seen at 58° -->
        <g class="cup__bean" data-cup-bean{% if cup_state == 'empty' %} opacity="0"{% endif %}>
          <g transform="scale(1 ${S}) rotate(-30)">
            <ellipse rx="6.4" ry="9.4" fill="url(#cupFoam)"/>
            <path d="M.3-7.2C-3.1-3.4 2.9 3.2-.3 7.2" fill="none" style="stroke: color-mix(in oklab, #AE5041 45%, #3A1A0B)" stroke-width="1.3" stroke-linecap="round"/>
          </g>
        </g>
      </g>
      <g class="cup__ripples" data-cup-ripples aria-hidden="true">
        <ellipse class="cup__ripple" rx="3" ry="${f(3 * S)}" fill="none" stroke="#FFF7DE" stroke-opacity=".55" stroke-width=".35" opacity="0"/>
        <ellipse class="cup__ripple" rx="3" ry="${f(3 * S)}" fill="none" stroke="#FFF7DE" stroke-opacity=".55" stroke-width=".35" opacity="0"/>
        <ellipse class="cup__ripple" rx="3" ry="${f(3 * S)}" fill="none" stroke="#FFF7DE" stroke-opacity=".55" stroke-width=".35" opacity="0"/>
      </g>
    </g>
  </g>

  <!-- Last stretch of the pour inside the cup (scaleY from the top; transform only) and the final drop -->
  <rect class="cup__pour" data-cup-pour x="${f(CX - 0.85)}" y="0" width="1.7" height="${f(baseCy)}" fill="url(#cupPour)" transform="scale(1 0)"/>
  <ellipse class="cup__drop" data-cup-drop cx="${CX}" cy="0" rx=".85" ry="1.4" fill="#210000" opacity="0"/>
</svg>
`;

writeFileSync(path.join(root, 'snippets', 'cup-svg.liquid'), svg);
console.log(`cup-svg.liquid written. base surface cy=${f(baseCy)} mm, full surface cy=${f(fullCy)} mm, full r=${f(r(FULL_H))} mm`);
